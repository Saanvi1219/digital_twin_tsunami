"""
gemini_agent.py

Gemini-based Decision Intelligence Agent.

Responsibilities
----------------
- Receive outputs from the integrated tsunami pipeline
- Interpret simulation and DTII results
- Explain the current Digital Twin state
- Generate risk interpretation
- Generate decision-support recommendations

Important
---------
This agent DOES NOT perform:
- tsunami physics
- wave propagation
- inundation calculation
- DTII calculation
- geospatial preprocessing

Those operations remain in their respective modules.
"""

from __future__ import annotations

import json
import os
from typing import Any, Dict, Optional

from dotenv import load_dotenv
from google import genai
from google.genai import types


# ==========================================================
# LOAD ENVIRONMENT VARIABLES
# ==========================================================

load_dotenv()


class GeminiTsunamiAgent:
    """
    LLM decision-support agent for the tsunami Digital Twin.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-3.5-flash",
    ):
        """
        Initialize Gemini.

        API key priority:
        1. Explicit api_key argument
        2. GEMINI_API_KEY from environment/.env
        """

        self.api_key = (
            api_key
            or os.getenv("GEMINI_API_KEY")
        )

        self.model = model

        if not self.api_key:
            raise RuntimeError(
                "GEMINI_API_KEY is not set.\n"
                "Create a .env file in the project root:\n\n"
                "GEMINI_API_KEY=YOUR_API_KEY\n"
            )

        self.client = genai.Client(
            api_key=self.api_key
        )

    # ==========================================================
    # PUBLIC API
    # ==========================================================

    def analyse(
        self,
        features: Dict[str, Any],
        simulation_summary: Dict[str, Any],
        dtii: Dict[str, Any],
        twin_state: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """
        Analyse outputs from the tsunami pipeline.
        """

        payload = {
            "environmental_features":
                self._safe_serialize(features),

            "simulation":
                self._safe_serialize(
                    simulation_summary
                ),

            "dtii":
                self._safe_serialize(dtii),

            "digital_twin":
                self._safe_serialize(twin_state)
                if twin_state is not None
                else None,
        }

        prompt = self._build_prompt(payload)

        try:

            response = self.client.models.generate_content(
                model=self.model,
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=
                        self._system_instruction(),

                    temperature=0.2,

                    max_output_tokens=1200,
                ),
            )

            text = self._extract_text(response)

        except Exception as exc:

            text = (
                "Gemini analysis failed: "
                f"{str(exc)}"
            )

        return {
            "agent": "GeminiTsunamiAgent",

            "model": self.model,

            "analysis": text,

            "input": payload,
        }

    # ==========================================================
    # SYSTEM INSTRUCTION
    # ==========================================================

    def _system_instruction(self) -> str:
        """
        Define the role and limitations of the LLM.
        """

        return """
You are the Decision Intelligence Agent of an Adaptive
Tsunami Digital Twin.

Your role is to interpret outputs generated by the
scientific and computational components of the system.

You are NOT the scientific simulation engine.

You must NOT perform or invent:

- tsunami physics
- wave propagation
- inundation calculation
- geospatial preprocessing
- earthquake measurements
- ground deformation measurements
- DTII calculation

Treat supplied numerical values as authoritative.

You must NOT modify or recalculate supplied values.

Your responsibilities are:

1. Explain the current tsunami situation.
2. Interpret the DTII score and risk level.
3. Explain the major contributing factors.
4. Identify uncertainty and missing information.
5. Explain Digital Twin health and state when available.
6. Provide practical decision-support recommendations.
7. Clearly distinguish computed results from recommendations.

Important:

- Never invent measurements.
- Never invent missing datasets.
- Never claim that an official evacuation order has been issued.
- Recommendations are decision support only.
- If validation quality is LOW, explicitly mention this limitation.
- If important datasets are missing, explicitly mention them.
- Keep the interpretation technically grounded.
- Use the supplied values exactly.
- Do not silently change units or values.

The final response should be concise enough for a
disaster-management dashboard.
"""

    # ==========================================================
    # PROMPT BUILDER
    # ==========================================================

    def _build_prompt(
        self,
        payload: Dict[str, Any],
    ) -> str:
        """
        Build the user prompt sent to Gemini.
        """

        serialized = json.dumps(
            payload,
            indent=2,
            default=str,
        )

        return f"""
Analyse the following outputs from an Adaptive Tsunami
Digital Twin.

The information below was generated by the project's
preprocessing, simulation, validation, DTII, risk,
and Digital Twin components.

Do NOT recalculate any supplied values.

============================================================
INPUT DATA
============================================================

{serialized}

============================================================
REQUIRED ANALYSIS
============================================================

Provide the following sections:

1. SITUATION SUMMARY

Briefly describe the simulated tsunami situation using
only the supplied information.

2. DTII INTERPRETATION

State:

- DTII score
- DTII level

exactly as supplied.

Explain what the result indicates.

3. KEY DRIVERS

Identify the strongest contributing features.

Explain their importance without creating new values.

4. SIMULATION IMPACT

Interpret:

- maximum wave height
- maximum run-up
- flooded area
- other supplied simulation outputs

Use the supplied values exactly.

5. VALIDATION AND CONFIDENCE

If validation information is available:

- report the validation confidence
- report prediction quality
- mention important metrics
- explain limitations

6. DIGITAL TWIN STATUS

If Digital Twin information is available:

- state whether it is ready
- mention version
- mention history/events/synchronization if available
- mention warnings or errors

7. DECISION SUPPORT

Provide practical priorities for emergency planners,
such as:

- continued monitoring
- additional observations
- model validation
- evacuation planning
- resource prioritization
- data acquisition

Do not issue an official evacuation order.

8. UNCERTAINTIES

Clearly identify:

- missing datasets
- low validation confidence
- assumptions
- missing observations
- other limitations

============================================================
IMPORTANT
============================================================

Do not invent values.

Do not modify supplied numerical values.

Do not perform independent tsunami calculations.

Clearly distinguish COMPUTED RESULTS from
DECISION-SUPPORT RECOMMENDATIONS.
"""

    # ==========================================================
    # RESPONSE EXTRACTION
    # ==========================================================

    @staticmethod
    def _extract_text(
        response: Any,
    ) -> str:
        """
        Safely extract generated text from Gemini.
        """

        try:
            text = response.text

        except Exception:
            text = None

        if text:
            return text.strip()

        return (
            "Gemini returned no textual analysis."
        )

    # ==========================================================
    # SAFE SERIALIZATION
    # ==========================================================

    @classmethod
    def _safe_serialize(
        cls,
        value: Any,
    ) -> Any:
        """
        Convert project objects into JSON-safe structures.

        Prevents NumPy arrays, dataclasses and custom
        Digital Twin objects from breaking the Gemini request.
        """

        if value is None:
            return None

        # ------------------------------------------
        # Primitive values
        # ------------------------------------------

        if isinstance(
            value,
            (
                str,
                int,
                float,
                bool,
            ),
        ):
            return value

        # ------------------------------------------
        # Dictionary
        # ------------------------------------------

        if isinstance(
            value,
            dict,
        ):

            return {
                str(key):
                    cls._safe_serialize(item)

                for key, item in value.items()
            }

        # ------------------------------------------
        # List / Tuple
        # ------------------------------------------

        if isinstance(
            value,
            (list, tuple),
        ):

            return [
                cls._safe_serialize(item)
                for item in value
            ]

        # ------------------------------------------
        # NumPy arrays / objects
        # ------------------------------------------

        if hasattr(
            value,
            "tolist",
        ):

            try:
                return value.tolist()

            except Exception:
                pass

        # ------------------------------------------
        # Dataclass / custom object
        # ------------------------------------------

        if hasattr(
            value,
            "__dict__",
        ):

            try:

                return {
                    str(key):
                        cls._safe_serialize(item)

                    for key, item
                    in vars(value).items()
                }

            except Exception:
                pass

        # ------------------------------------------
        # Dataclass with slots
        # ------------------------------------------

        if hasattr(
            value,
            "__dataclass_fields__",
        ):

            try:

                result = {}

                for key in value.__dataclass_fields__:

                    result[key] = cls._safe_serialize(
                        getattr(value, key)
                    )

                return result

            except Exception:
                pass

        # ------------------------------------------
        # Fallback
        # ------------------------------------------

        return str(value)